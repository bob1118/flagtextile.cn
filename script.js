// Language switch
document.getElementById('lang-zh').addEventListener('click', () => switchLanguage('zh'));
document.getElementById('lang-en').addEventListener('click', () => switchLanguage('en'));

function switchLanguage(lang) {
    try { localStorage.setItem('lang', lang); } catch (e) {}
    document.getElementById('lang-zh').classList.toggle('active', lang === 'zh');
    document.getElementById('lang-en').classList.toggle('active', lang === 'en');
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    document.title = languages[lang]['home-title'];

    const elements = document.querySelectorAll('[data-lang]');
    const currentYear = new Date().getFullYear();
    elements.forEach(el => {
        const key = el.getAttribute('data-lang');
        if (languages[lang][key]) {
            el.textContent = languages[lang][key].replace('{year}', currentYear);
        }
    });

    // Keep product image alt text in sync with the translated product name
    document.querySelectorAll('.product-item').forEach(item => {
        const nameEl = item.querySelector('h3');
        const img = item.querySelector('.thumb img');
        if (nameEl && img) {
            img.alt = nameEl.textContent;
        }
    });
}

