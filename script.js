// Category tabs
document.querySelectorAll('[data-cat-tab]').forEach(tab => {
    tab.addEventListener('click', () => switchTab(tab.getAttribute('data-cat-tab')));
});

function switchTab(name) {
    document.querySelectorAll('[data-cat-tab]').forEach(t => {
        const on = t.getAttribute('data-cat-tab') === name;
        t.classList.toggle('is-active', on);
        t.setAttribute('aria-selected', on ? 'true' : 'false');
        t.tabIndex = on ? 0 : -1;
    });
    document.querySelectorAll('.category-panel').forEach(p => {
        p.classList.toggle('is-active', p.id === 'cat-' + name);
    });
}

// Modal gallery viewer (only cards carrying data-images open it)
const modal = document.getElementById('modal');
const modalImg = document.getElementById('modal-img');
const modalCount = document.getElementById('modal-count');
const captionText = document.getElementById('caption');
const modalDesc = document.getElementById('modal-desc');
const modalSpec = document.getElementById('modal-spec');
const closeBtn = document.getElementsByClassName('close')[0];
const prevBtn = document.getElementById('modal-prev');
const nextBtn = document.getElementById('modal-next');
let galleryImages = [];
let galleryIndex = 0;

function showGalleryImage() {
    modalImg.src = galleryImages[galleryIndex];
    modalCount.textContent = (galleryIndex + 1) + ' / ' + galleryImages.length;
    const multi = galleryImages.length > 1;
    prevBtn.style.display = multi ? '' : 'none';
    nextBtn.style.display = multi ? '' : 'none';
    modalCount.style.display = multi ? '' : 'none';
}

document.querySelectorAll('.product-item[data-images]').forEach(item => {
    item.addEventListener('click', function() {
        try {
            galleryImages = JSON.parse(this.getAttribute('data-images'));
        } catch (e) {
            galleryImages = [];
        }
        if (!galleryImages.length) return;
        galleryIndex = 0;
        showGalleryImage();
        const nameEl = this.querySelector('h3');
        modalImg.alt = nameEl.textContent;
        captionText.textContent = nameEl.textContent;
        modalDesc.textContent = this.querySelector('.card-desc').textContent;
        const chip = this.querySelector('.spec-chip');
        if (chip) {
            modalSpec.textContent = chip.textContent;
            modalSpec.style.display = '';
        } else {
            modalSpec.style.display = 'none';
        }
        modal.style.display = 'flex';
    });
});

prevBtn.onclick = function() {
    galleryIndex = (galleryIndex - 1 + galleryImages.length) % galleryImages.length;
    showGalleryImage();
}

nextBtn.onclick = function() {
    galleryIndex = (galleryIndex + 1) % galleryImages.length;
    showGalleryImage();
}

closeBtn.onclick = function() {
    modal.style.display = 'none';
}

window.onclick = function(event) {
    if (event.target === modal) {
        modal.style.display = 'none';
    }
}

document.addEventListener('keydown', function(event) {
    if (event.key === 'Escape') {
        modal.style.display = 'none';
    }
});

// Touch swipe for modal gallery (mobile)
let touchStartX = null;
modal.addEventListener('touchstart', function(event) {
    touchStartX = event.touches[0].clientX;
}, { passive: true });

modal.addEventListener('touchend', function(event) {
    if (touchStartX === null) return;
    const deltaX = event.changedTouches[0].clientX - touchStartX;
    touchStartX = null;
    if (Math.abs(deltaX) < 40 || galleryImages.length < 2) return;
    galleryIndex = (galleryIndex + (deltaX < 0 ? 1 : -1) + galleryImages.length) % galleryImages.length;
    showGalleryImage();
});

